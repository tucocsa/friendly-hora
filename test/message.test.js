import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { test } from 'node:test';
import { formatMessage } from '../src/message.js';
import { buildSchedule } from '../src/schedule.js';

const fact = JSON.parse(await readFile(new URL('./fixtures/fact-2026-10-08.json', import.meta.url), 'utf8'));

const day = (date, off, maybe = []) => ({ date, off, maybe });

test('повідомлення для фікстури 8–9 жовтня', () => {
  assert.equal(
    formatMessage(buildSchedule(fact, 'GPV5.1'), ['2026-10-09']),
    [
      'Графік відключень змінився',
      'Чт, 8 жовтня\nБез світла: 00:00–00:30, 07:00–14:30, 17:30–21:00',
      'Пт, 9 жовтня (оновлено)\nБез світла: 14:30–18:30',
    ].join('\n\n'),
  );
});

test('нічне відключення через північ показується одним інтервалом', () => {
  const days = [
    day('2026-10-09', ['14:30-18:30', '22:00-24:00']),
    day('2026-10-10', ['00:00-02:00', '07:00-10:30'], ['23:00-24:00']),
  ];
  assert.equal(
    formatMessage({ days }, []),
    [
      'Графік відключень змінився',
      'Пт, 9 жовтня\nБез світла: 14:30–18:30, 22:00 – сб 02:00',
      'Сб, 10 жовтня\nБез світла: 07:00–10:30\nМожливі відключення: 23:00–24:00',
    ].join('\n\n'),
  );
});

test('день лише з продовженням нічного відключення і день без відключень', () => {
  const days = [day('2026-10-09', ['23:00-24:00']), day('2026-10-10', ['00:00-01:00']), day('2026-10-11', [])];
  assert.equal(
    formatMessage({ days }, []),
    [
      'Графік відключень змінився',
      'Пт, 9 жовтня\nБез світла: 23:00 – сб 01:00',
      'Сб, 10 жовтня\nІнших відключень немає',
      'Нд, 11 жовтня\nВідключень немає',
    ].join('\n\n'),
  );
});

test('через пропущену дату інтервали не зливаються', () => {
  const days = [day('2026-10-09', ['23:00-24:00']), day('2026-10-11', ['00:00-01:00'])];
  assert.match(formatMessage({ days }, []), /Пт, 9 жовтня\nБез світла: 23:00–24:00\n\nНд, 11 жовтня\nБез світла: 00:00–01:00/);
});
